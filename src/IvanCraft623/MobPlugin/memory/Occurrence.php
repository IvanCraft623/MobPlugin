declare(strict_types=1);

namespace IvanCraft623\MobPlugin\memory;

/**
 * Something that happened between two entities, as the first one remembers it.
 */
enum Occurrence{
	/**
	 * The other entity hurt the subject.
	 */
	case HURT_BY;
	/**
	 * The subject hurt the other entity.
	 */
	case HURT;
	/**
	 * A player hurt the subject.
	 */
	case HURT_BY_PLAYER;
}
