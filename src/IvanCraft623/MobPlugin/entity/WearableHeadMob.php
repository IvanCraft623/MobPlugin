declare(strict_types=1);

namespace IvanCraft623\MobPlugin\entity;

use pocketmine\block\utils\MobHeadType;

/**
 * A mob that has a head item other entities can wear, which may affect how well mobs of its kind see them.
 */
interface WearableHeadMob{

	public function getMobHeadType() : MobHeadType;

	/**
	 * Multiplier on the visibility of an entity wearing this mob's head, 1.0 for none.
	 */
	public function getHeadVisibilityFactor() : float;
}