declare(strict_types=1);

namespace IvanCraft623\MobPlugin\entity;

/**
 * For mobs that move in hops: in the air they accelerate with a share of their movement speed.
 *
 * @phpstan-require-extends Mob
 */
trait HopperTrait{

	private const AIR_SPEED_FACTOR = 0.1; //times the movement speed

	public function getAirMovementSpeed() : float{
		return self::AIR_SPEED_FACTOR * $this->getMovementSpeed();
	}
}