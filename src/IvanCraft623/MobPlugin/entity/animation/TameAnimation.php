declare(strict_types=1);

namespace IvanCraft623\MobPlugin\entity\animation;

use IvanCraft623\MobPlugin\entity\Mob;
use pocketmine\entity\animation\Animation;
use pocketmine\network\mcpe\protocol\ActorEventPacket;
use pocketmine\network\mcpe\protocol\types\ActorEvent;

/**
 * The hearts of a mob that was tamed or trusts a player, or the smoke of one that didn't.
 */
final class TameAnimation implements Animation{

	public function __construct(private Mob $mob, private bool $success){}

	public function encode() : array{
		return [
			ActorEventPacket::create($this->mob->getId(), $this->success ? ActorEvent::TAME_SUCCESS : ActorEvent::TAME_FAIL, 0, null)
		];
	}
}
