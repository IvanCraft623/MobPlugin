declare(strict_types=1);

namespace IvanCraft623\MobPlugin\entity\genetics;

final class AlleleRange{

	/**
	 * @param int $min least allele in the range, inclusive
	 * @param int $max most allele in the range, inclusive
	 */
	public function __construct(
		public readonly int $min,
		public readonly int $max
	){}

	public function contains(int $allele) : bool{
		return $allele >= $this->min && $allele <= $this->max;
	}
}